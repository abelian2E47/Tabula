/**
 * Fetch the search engines' brand marks and inline them into the bundle.
 *
 * The marks are inlined rather than shipped as image files on purpose: a new
 * tab is opened dozens of times a day, and five separate image requests per
 * open — even cached ones — are five requests the page should not make. Inlined
 * paths cost nothing at runtime and are drawn in the surrounding ink, so a mark
 * reads on a light page, a dark page and a photograph alike.
 *
 * Two sources, because no single one covers all five:
 *
 *   Simple Icons (CC0-1.0) — google, baidu, bilibili, github. It carries no
 *   Microsoft marks at all, so Bing comes from Commons instead:
 *
 *   Wikimedia Commons, "Bing Fluent Logo.svg" — public domain. It ships as
 *   three gradient-filled paths in a 678x1024 box, so the geometry is kept and
 *   the fills are dropped, then normalised into the 24x24 box the other four
 *   are drawn in.
 *
 * Re-run to refresh:  node tools/fetch-engine-marks.mjs
 */

import { writeFile } from 'node:fs/promises'

const SIMPLE_ICONS = 'https://unpkg.com/simple-icons@15.0.0/icons/'

/** Simple Icons slug → the id used in the extension and the brand's colour. */
const SIMPLE = [
  { id: 'google', slug: 'google', brand: '#4285F4' },
  { id: 'baidu', slug: 'baidu', brand: '#2932E1' },
  { id: 'bilibili', slug: 'bilibili', brand: '#00A1D6' },
  { id: 'github', slug: 'github', brand: '#181717' },
]

const BING = {
  id: 'bing',
  brand: '#258FFB',
  url: 'https://upload.wikimedia.org/wikipedia/commons/9/9c/Bing_Fluent_Logo.svg',
  /** Source box, so the glyph can be centred in the 24x24 the others use. */
  box: { width: 678, height: 1024 },
}

const marks = []

/* ---- Simple Icons: one 24x24 path each -------------------------------- */

for (const engine of SIMPLE) {
  const response = await fetch(`${SIMPLE_ICONS}${engine.slug}.svg`)
  if (!response.ok) throw new Error(`${engine.slug}: HTTP ${response.status}`)
  const path = /<path[^>]*\sd="([^"]+)"/.exec(await response.text())?.[1]
  if (!path) throw new Error(`${engine.slug}: no path`)
  marks.push({ id: engine.id, brand: engine.brand, paths: [{ d: path }] })
  console.log(`ok ${engine.id.padEnd(9)} simple-icons  ${path.length}B`)
}

/* ---- Bing: three paths from Commons, renormalised --------------------- */

{
  const response = await fetch(BING.url)
  if (!response.ok) throw new Error(`bing: HTTP ${response.status}`)
  const svg = await response.text()

  const paths = [...svg.matchAll(/<path\b([^>]*?)\/?>/g)].map((match) => {
    const d = /\sd="([^"]+)"/.exec(match[1])?.[1]
    if (!d) throw new Error('bing: a path has no d')
    return /fill-rule="evenodd"/.test(match[1]) ? { d, rule: 'evenodd' } : { d }
  })
  if (paths.length === 0) throw new Error('bing: no paths')

  // Fit the tallest dimension to the 24 box and centre what is left over.
  const scale = 24 / BING.box.height
  const x = (24 - BING.box.width * scale) / 2
  const transform = `translate(${x.toFixed(3)} 0) scale(${Number(scale.toFixed(8))})`

  marks.push({ id: BING.id, brand: BING.brand, paths, transform })
  console.log(`ok ${BING.id.padEnd(9)} commons      ${paths.length} paths, ${transform}`)
}

/* ---- Emit ------------------------------------------------------------- */

const entry = (mark) => {
  const paths = mark.paths
    .map((p) => `      { d: '${p.d}'${p.rule ? `, rule: '${p.rule}'` : ''} },`)
    .join('\n')
  return `  ${mark.id}: {
    brand: '${mark.brand}',
${mark.transform ? `    transform: '${mark.transform}',\n` : ''}    paths: [
${paths}
    ],
  },`
}

const body = `/**
 * Engine marks, generated by \`tools/fetch-engine-marks.mjs\` — do not hand-edit.
 *
 * Sources: Simple Icons (CC0-1.0) for google, baidu, bilibili and github;
 * Wikimedia Commons' "Bing Fluent Logo.svg" (public domain) for bing, whose
 * geometry is reused with its gradient fills dropped. Each mark is one or more
 * filled paths inside a 24x24 box and is drawn in \`currentColor\`: the brand
 * colour is kept for tinting only, because a brand colour is safe as ink solely
 * on the background it was chosen for, and a tile here can be any colour.
 */

export interface EnginePath {
  d: string
  rule?: 'evenodd'
}

export interface EngineMark {
  /** The brand's own colour. Used as a tint, never as the mark's fill. */
  brand: string
  /** Present when the source geometry needs placing into the 24x24 box. */
  transform?: string
  paths: EnginePath[]
}

export const ENGINE_MARKS: Record<string, EngineMark> = {
${marks.map(entry).join('\n')}
}
`

await writeFile('src/assets/engines.ts', body)
console.log(`wrote src/assets/engines.ts — ${marks.length} marks, ${body.length}B`)
